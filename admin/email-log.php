<?php
require '../includes/db.php';
require '../includes/auth.php';
require '../includes/mail_config.php';
requireRole(['coordinator']);

$user = currentUser();
$activePage = 'email-log';

// View one email's body if requested.
$viewEmail = null;
if (isset($_GET['id'])) {
    $stmt = $db->prepare("SELECT * FROM sent_emails WHERE id = ?");
    $stmt->execute([(int)$_GET['id']]);
    $viewEmail = $stmt->fetch();
}

$emails = $db->query("
    SELECT id, to_email, to_name, subject, category, status, provider_message,
           created_at, sent_at
    FROM sent_emails
    ORDER BY id DESC
    LIMIT 200
")->fetchAll();

$counts = ['demo' => 0, 'sent' => 0, 'failed' => 0];
foreach ($db->query("SELECT status, COUNT(*) n FROM sent_emails GROUP BY status") as $r) {
    $counts[$r['status']] = (int)$r['n'];
}

require '../includes/header.php';
?>

<div class="page-header">
    <h1>Email log</h1>
    <p>Every message produced by the Mailer (Brevo adapter). Mode is currently
       <strong><?= MAIL_DEMO_MODE ? 'DEMO — messages are recorded, not sent' : 'LIVE — messages are sent via Brevo' ?></strong>.</p>
</div>

<div class="card">
    <div style="display:flex;gap:18px;flex-wrap:wrap;">
        <span class="badge badge-pending">Demo: <?= $counts['demo'] ?></span>
        <span class="badge badge-open">Sent: <?= $counts['sent'] ?></span>
        <span class="badge badge-closed">Failed: <?= $counts['failed'] ?></span>
    </div>
</div>

<?php if ($viewEmail): ?>
    <div class="card">
        <h3 style="margin-top:0;">Message #<?= (int)$viewEmail['id'] ?></h3>
        <div class="field-row"><span>To</span><span><?= htmlspecialchars(($viewEmail['to_name'] ? $viewEmail['to_name'] . ' · ' : '') . $viewEmail['to_email']) ?></span></div>
        <div class="field-row"><span>Subject</span><span><?= htmlspecialchars($viewEmail['subject']) ?></span></div>
        <div class="field-row"><span>Category</span><span><?= htmlspecialchars($viewEmail['category'] ?? '—') ?></span></div>
        <div class="field-row"><span>Status</span><span><?= htmlspecialchars($viewEmail['status']) ?></span></div>
        <div class="field-row"><span>Provider message</span><span><?= htmlspecialchars($viewEmail['provider_message'] ?? '—') ?></span></div>
        <div style="margin-top:14px;border:1px solid #e5e7eb;border-radius:6px;overflow:hidden;">
            <?= $viewEmail['body_html'] /* trusted: generated by our own Mailer::wrap */ ?>
        </div>
        <p style="margin-top:14px;"><a href="<?= BASE_URL ?>/admin/email-log.php">← Back to log</a></p>
    </div>
<?php endif; ?>

<?php if (empty($emails)): ?>
    <div class="card empty-state"><p>No emails yet. Publish a matching round to generate match notifications.</p></div>
<?php else: ?>
    <div class="card">
        <table>
            <thead>
                <tr><th>#</th><th>To</th><th>Subject</th><th>Category</th><th>Status</th><th>When</th></tr>
            </thead>
            <tbody>
            <?php foreach ($emails as $m): ?>
                <?php
                    $cls = $m['status'] === 'sent' ? 'open'
                         : ($m['status'] === 'failed' ? 'closed' : 'pending');
                ?>
                <tr>
                    <td class="offer-meta">
                        <a href="<?= BASE_URL ?>/admin/email-log.php?id=<?= (int)$m['id'] ?>">
                            <?= (int)$m['id'] ?>
                        </a>
                    </td>
                    <td><?= htmlspecialchars($m['to_name'] ?: $m['to_email']) ?></td>
                    <td><?= htmlspecialchars($m['subject']) ?></td>
                    <td><span class="offer-meta"><?= htmlspecialchars($m['category'] ?? '—') ?></span></td>
                    <td><span class="badge badge-<?= $cls ?>"><?= htmlspecialchars($m['status']) ?></span></td>
                    <td><?= htmlspecialchars(date('d M Y, H:i', strtotime($m['created_at']))) ?></td>
                </tr>
            <?php endforeach; ?>
            </tbody>
        </table>
    </div>
<?php endif; ?>

<?php require '../includes/footer.php'; ?>
